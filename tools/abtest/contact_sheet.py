#!/usr/bin/env python3
"""contact_sheet.py — dump sampled frames of a perf demo for human review.

Perf baseline v2 (.scratch/levelmesh-impl/issues/02-perf-baseline-v2.md):
every perf demo must show real geometry. This replays a demo in the A/B
capture mode (r_ab_capture: synthetic clock, one sim tic per rendered
frame, so capture tick N is demo tic N), captures the listed ticks, and
tiles them into one labelled PNG.

Usage:
  contact_sheet.py --demo demos/v2/DOOM2_MAP01.lmp --map MAP01 \\
      --iwad DOOM2.WAD [--pwad myhouse.pk3] [--ticks 50,150,...] \\
      [--every 100 --offset 50 --tics 2600] --out sheets/DOOM2_MAP01.png

Requires Pillow. WADs under build/wads/; run unsandboxed on a real GPU.
"""
import argparse
import os
import shutil
import subprocess
import sys

from PIL import Image, ImageDraw

KIT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(KIT, "..", ".."))
BUILD = os.path.join(ROOT, "build")

PINS = """\
// generated by contact_sheet.py
exec "{cfg}"
set vid_preferbackend {backend}
set language english
set uiscale 1
set screenshot_quiet 1
set r_ab_capture {ticks}:{outdir}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--demo", required=True)
    ap.add_argument("--map", required=True, help="map lump name (PNG prefix)")
    ap.add_argument("--iwad", required=True, help="base IWAD under build/wads/")
    ap.add_argument("--pwad", default="", help="PWAD under build/wads/")
    ap.add_argument("--ticks", default="", help="explicit tick list")
    ap.add_argument("--every", type=int, default=100)
    ap.add_argument("--offset", type=int, default=50)
    ap.add_argument("--tics", type=int, default=2600)
    ap.add_argument("--backend", type=int, default=1, help="0 GL33, 1 Vulkan")
    ap.add_argument("--thumb", type=int, default=480, help="thumbnail width")
    ap.add_argument("--cols", type=int, default=6)
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--out", required=True)
    ap.add_argument("--set", action="append", default=[], metavar="'CVAR VALUE'",
                    help="extra cvar pin (repeatable)")
    a = ap.parse_args()

    if a.ticks:
        ticks = [int(t) for t in a.ticks.split(",") if t.strip()]
    else:
        ticks = list(range(a.offset, a.tics, a.every))
    # Stable per-sheet work dir. The capture writes <outdir>/<map>_<tick>.png
    # through M_ScreenShot, which does not create missing directories for an
    # explicit filename: the output dir must exist before the engine starts.
    stem = os.path.splitext(os.path.basename(a.out))[0]
    tmp = os.path.join(KIT, "logs", "sheet_" + stem)
    shutil.rmtree(tmp, ignore_errors=True)
    shots = os.path.join(tmp, "png")
    os.makedirs(shots, exist_ok=True)
    pins = os.path.join(tmp, "pins.cfg")
    with open(pins, "w") as f:
        f.write(PINS.format(cfg=os.path.join(KIT, "baseline.cfg"), backend=a.backend,
                            ticks=",".join(map(str, ticks)), outdir=shots))
        for kv in a.set:
            f.write(f"set {kv}\n")
    cmd = [os.path.join(BUILD, "uzdoom"), "-iwad", os.path.join("wads", a.iwad),
           "-nomonsters", "-rngseed", "12345", "-width", "1280", "-height", "720",
           "-exec", pins, "-playdemo", os.path.abspath(a.demo)]
    if a.pwad:
        cmd[3:3] = ["-file", os.path.join("wads", a.pwad)]
    log = os.path.join(tmp, "stdout.log")
    with open(log, "wb") as out:
        try:
            subprocess.run(cmd, cwd=BUILD, stdout=out, stderr=subprocess.STDOUT,
                           timeout=a.timeout)
        except subprocess.TimeoutExpired:
            print(f"warning: engine timed out ({a.timeout}s); tiling what exists",
                  file=sys.stderr)
    with open(log, errors="replace") as f:
        if "llvmpipe" in f.read():
            sys.exit("llvmpipe in stdout: run unsandboxed on the real GPU")

    tiles = []
    for t in ticks:
        p = os.path.join(shots, f"{a.map}_{t}.png")
        if not os.path.isfile(p):
            print(f"warning: missing capture for tick {t}", file=sys.stderr)
            continue
        im = Image.open(p).convert("RGB")
        h = round(im.height * a.thumb / im.width)
        im = im.resize((a.thumb, h))
        ImageDraw.Draw(im).text((6, 6), f"tic {t}", fill=(255, 255, 0))
        tiles.append(im)
    if not tiles:
        sys.exit(f"no captures produced (see {log})")
    cols = min(a.cols, len(tiles))
    rows = (len(tiles) + cols - 1) // cols
    tw, th = tiles[0].size
    sheet = Image.new("RGB", (cols * tw, rows * th))
    for i, im in enumerate(tiles):
        sheet.paste(im, ((i % cols) * tw, (i // cols) * th))
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    sheet.save(a.out)
    print(f"wrote {a.out}: {len(tiles)}/{len(ticks)} frames")


if __name__ == "__main__":
    main()
